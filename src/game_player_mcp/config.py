"""Настройки сервера — ровно те поля, которые нужны исполнителю.

Полное приложение тянет за собой десятки параметров модели, ключей и UI.
Здесь ничего этого нет: MCP-сервер не думает, он только смотрит и действует,
поэтому конфиг сведён к четырём полям.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class Config:
    """Параметры захвата и ввода."""

    #: Двигать мышь абсолютно или относительно. Для оконных игр нужен первый.
    input_mode: str = "scancode"

    #: Как набирать текст: "unicode" надёжнее для не-латинских раскладок.
    type_mode: str = "unicode"

    #: Пауза между действиями внутри одного шага, секунды.
    action_delay: float = 0.05

    #: Ничего не отправлять в игру, только печатать, что было бы сделано.
    dry_run: bool = False

    #: Работать, не забирая фокус: захват через PrintWindow, ввод через
    #: PostMessage. Требует в настройках игры ``pauseOnLostFocus:false`` и
    #: ``rawMouseInput:false``, иначе игра перехватит управление обратно.
    background_mode: bool = False

    #: Клавиша аварийного сброса (используется приложением, серверу нужна для
    #: совместимости с исполнителем).
    panic_key: str = "f12"
